"""Stage-3 VERSIONED CORRECTED FREEZE (protocol Section 48).

Defect: src/avoi/evaluation/stage2.py's module-level `CONFLICT` dict (an IAM-only evidence-polarity-conflict flag,
reused unchanged from Stage 2) was left set by WP1's confirm() loop and never cleared before WP2's confirm() called
the same reused `S.tune()` / `S.rows_at()` functions on AIT/CERT data. AIT/CERT have no such flag, so `rows_at()`
indexed the stale 256-length IAM array with AIT/CERT-sized indices, raising IndexError. The crash happened during
WP2-AIT threshold tuning, entirely AFTER the adequacy freeze/decisions step.

Why the frozen adequacy decisions do not need to be redone: `adequacy_phase()` (WP1, WP2-AIT, WP2-CERT) computes
metrics directly from model posteriors via `AQ.point_metrics`/`AQ.group_bootstrap` and never calls `rows_at()` or
`S.tune()` - the buggy code path is confirm()-phase only. ADEQUACY_DECISIONS_STAGE3.json is therefore unaffected and
is NOT regenerated by this correction.

Correction: `S.CONFLICT["flags"] = None` added at the start of `run_wp2_ait.py::confirm()` and
`run_wp2_cert.py::confirm()`, so AIT/CERT rows always fall back to `conflict=False` (rows_at's documented behaviour
when no conflict flag exists for a domain), matching AIT/CERT's actual absence of this label-free diagnostic.

Usage: python experiments/stage3/freeze_correction_v2.py
"""
from __future__ import annotations

import datetime as dt
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "experiments"))
sys.path.insert(0, str(ROOT / "experiments" / "stage3"))

from common import sha256_file  # noqa: E402
from run_stage3 import DECISIONS, FREEZE, hashes  # noqa: E402

V1 = ROOT / "results" / "stage3" / "EXPERIMENT_FREEZE_STAGE3_v1_SUPERSEDED.json"


def main():
    if not V1.exists():
        raise SystemExit("v1 freeze not preserved; run this only as the documented correction step")
    v1 = json.loads(V1.read_text(encoding="utf-8"))
    if not DECISIONS.exists():
        raise SystemExit("ADEQUACY_DECISIONS_STAGE3.json missing; correction assumes adequacy was already frozen under v1")
    decisions_sha = json.loads(DECISIONS.read_text(encoding="utf-8"))["decisions_sha256"]

    rec = dict(v1)   # start from the v1 body, then update only what changed
    rec["freeze_version"] = 2
    rec["frozen_utc"] = dt.datetime.now(dt.timezone.utc).isoformat(timespec="seconds")
    rec["supersedes"] = {"file": "results/stage3/EXPERIMENT_FREEZE_STAGE3_v1_SUPERSEDED.json",
                         "combined_sha256": v1["hashes"]["combined_sha256"]}
    rec["correction"] = {
        "defect": ("src/avoi/evaluation/stage2.py's module-level CONFLICT dict (an IAM-only evidence-polarity-conflict "
                   "flag, reused unchanged from Stage 2) was left set by WP1's confirm() loop and never cleared before "
                   "WP2's confirm() called the same reused S.tune()/S.rows_at() on AIT/CERT data, indexing the stale "
                   "256-length IAM array out of bounds and crashing WP2-AIT confirm() with IndexError."),
        "scope_of_defect": ("confirm()-phase threshold tuning only. adequacy_phase() computes metrics directly from "
                            "model posteriors (AQ.point_metrics / AQ.group_bootstrap) and never calls rows_at()/tune(); "
                            "it never hit this code path."),
        "consequence": ("No confirmation output existed for WP2-AIT/WP2-CERT before this correction (the crash occurred "
                        "before any row was written). WP1 confirmation output, produced before the crash under v1, is "
                        "unaffected (IAM's own CONFLICT flag was set correctly for every IAM objective) and is kept."),
        "correction_applied": ("S.CONFLICT[\"flags\"] = None added at the start of run_wp2_ait.py::confirm() and "
                               "run_wp2_cert.py::confirm(), so AIT/CERT rows fall back to the documented conflict=False "
                               "default (AIT/CERT have no such flag)."),
        "adequacy_decisions_unaffected": True,
        "adequacy_decisions_sha256": decisions_sha,
        "primary_rules_changed": False,
        "statement": "No Stage-3 primary rule, threshold, partition, model-selection procedure, or hypothesis was changed."}
    rec["hashes"] = hashes()
    FREEZE.write_text(json.dumps(rec, indent=1, default=str), encoding="utf-8")
    print("Stage-3 freeze v2 (corrected):", rec["hashes"]["combined_sha256"], "freeze-file sha256:", sha256_file(FREEZE))
    print("supersedes v1:", v1["hashes"]["combined_sha256"])


if __name__ == "__main__":
    main()
